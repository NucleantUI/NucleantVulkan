extension RenderSettings {

    /// The Swift source of `RenderNode`: one `Context` case per node type,
    /// each routed through the slot's observe / update / destroy / image view /
    /// window resize. `module` is the target it is compiled into, so an import
    /// of itself is left out; `settingsName` is the file it was made from.
    public func renderNodeSource(module: String?, settingsName: String) -> String {
        var modules = ["NucleantVulkan", "CVulkan"]
        for name in imports where !modules.contains(name) && name != module {
            modules.append(name)
        }

        var lines = [
            "// Generated by RenderNodeBuilder from \(settingsName). Edit that file, not this one.",
            "",
        ]
        lines += modules.map { "import \($0)" }
        lines += [
            "",
            "public final class RenderNode: \(conformance), @unchecked Sendable {",
            "",
            "    public enum Context: RenderNodeContext {",
        ]
        lines += nodes.map { "        case \($0.caseName)(\($0.type)<RenderNode>)" }
        lines += [
            "    }",
            "",
            "    public let id: Int",
            "    public let context: Context",
            "    public var needsRender = true",
            "    public var compositesToWindow = true",
            "    public var compositeRect: SIMD4<Double>?",
            "    public var compositeScissor: SIMD4<Double>?",
            "",
            "    public init(id: Int, context: Context) {",
            "        self.id = id",
            "        self.context = context",
            "    }",
            "",
            "    public func observeContext() {",
        ]
        lines += contextSwitch(over: nodes.filter(\.observe)) { _ in "observe(node)" }
        lines += [
            "    }",
            "",
            "    public func update(device: Device, cmd: VkCommandBuffer) {",
            "        guard needsRender else { return }",
        ]
        lines += contextSwitch(over: nodes.filter(\.update)) { _ in "node.update(device, slot: self, cmd: cmd)" }
        lines += [
            "        needsRender = false",
            "    }",
            "",
            "    public func destroyResources(device: Device) {",
        ]
        lines += contextSwitch(over: nodes) { _ in "node.destroyResources(device)" }
        lines += [
            "    }",
            "",
            "    public func getImageView() -> VkImageView? {",
            "        guard compositesToWindow else { return nil }",
        ]
        lines += contextSwitch(over: nodes) { _ in "return node.imageView" }
        lines.append("    }")

        let resizing = nodes.filter(\.resizeToWindow)
        if !resizing.isEmpty {
            lines += [
                "",
                "    public func resizeToFitWindow(width: Int, height: Int, device: Device) {",
                "        guard compositesToWindow && compositeRect == nil else { return }",
            ]
            lines += contextSwitch(over: resizing) {
                "device.\($0.resizeFunction)(node, id: id, width: width, height: height)"
            }
            lines.append("    }")
        }

        lines += ["}", ""]
        return lines.joined(separator: "\n")
    }

    /// `switch context` running `body` for each of `chosen`, with every other
    /// case in one `break`. Nothing when none is chosen.
    private func contextSwitch(over chosen: [NodeSettings], _ body: (NodeSettings) -> String) -> [String] {
        guard !chosen.isEmpty else { return [] }
        var lines = ["        switch context {"]
        for node in chosen {
            lines += [
                "        case .\(node.caseName)(let node):",
                "            \(body(node))",
            ]
        }
        let others = nodes.filter { !chosen.contains($0) }
        if !others.isEmpty {
            lines += [
                "        case \(others.map { "." + $0.caseName }.joined(separator: ", ")):",
                "            break",
            ]
        }
        lines.append("        }")
        return lines
    }
}
